-- 아이콘 파일 번호가 0 인 단계는 아이콘 이름으로 게임에서 번호를 찾는다
do
	local probe
	local function FileID(name)
		local path = "Interface\\Icons\\" .. name
		if GetFileIDFromPath then
			local ok, id = pcall(GetFileIDFromPath, path)
			if ok and type(id) == "number" and id > 0 then return id end
		end
		probe = probe or (CreateFrame and CreateFrame("Frame"):CreateTexture())
		if probe and probe.GetTextureFileID then
			probe:SetTexture(path)
			local id = probe:GetTextureFileID()
			if type(id) == "number" and id > 0 then return id end
		end
	end
	for _, b in pairs(ns.TalentData.builds) do
		for _, s in ipairs(b.steps) do
			if s[1] == 0 and s[7] then s[1] = FileID(s[7]) or 0 end
		end
	end
end
